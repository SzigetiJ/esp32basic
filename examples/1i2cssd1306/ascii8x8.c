static const SAsciiAttributes gasAttributes[] = {
  {8, 8, false},
  {8, 6, false},
  {6, 4, false}
};

static const uint8_t *gapData[] = {
  &gaau8Ascii8x8[0][0],
  &gaau8Ascii8x6[0][0],
  &gaau8Ascii6x4[0][0]
};

// ============== Implementation ==============
// -------------- Internal functions --------------

static void _rotate_clockwise(uint8_t *pu8Dest, const uint8_t *pu8Src) {
  for (int i = 0; i < 8; ++i) {
    pu8Dest[i] = 0;
    for (int j = 0; j < 8; ++j) {
      pu8Dest[i] |= ((pu8Src[j] & (1 << (7 - i))) ? 1 : 0) << j;
    }
  }
}

// -------------- Interface functions --------------

/**
 * Tells what charsets are supported.
 * @return A bitset representing the set of support EAsciiCharset values.
 */
uint32_t ascii_supported_charsets() {
  return (1 << ASCII_CHRSET_8x8) | (1 << ASCII_CHRSET_8x6) | (1 << ASCII_CHRSET_6x4);
};

/**
 * Tells whether there is bitmap representation of an ascii code or not.
 * @param u8Code ASCII code.
 * @return The code has bitmap representation.
 */
SAsciiAttributes ascii_charset_attr(EAsciiCharset eCharset) {
  return gasAttributes[eCharset];
}

bool ascii_code_supported(EAsciiCharset eCharset, uint8_t u8Code) {
  return 32 <= u8Code && u8Code < 128;
}

/**
 * Puts the bitmap representation to a byte array.
 * The first bit (bit0 of the first byte) is the top left corner, and the bitmap is scanned top down
 * (i.e., MSB of the first byte is the bottom left corner).
 * @param pu8Dest Put the bitmap here.
 * @param eCharset Selected charset.
 * @param u8Code ASCII code of the symbol.
 * @return Number of set bytes.
 */
uint8_t ascii_get_tld(uint8_t *pu8Dest, EAsciiCharset eCharset, uint8_t u8Code) {
  uint8_t u8Idx = ascii_code_supported(eCharset, u8Code) ? u8Code - 32 : 95;
  const SAsciiAttributes *psAttr = &gasAttributes[eCharset];
  const uint8_t *pu8Data = gapData[eCharset];
  memcpy(pu8Dest, pu8Data + u8Idx * psAttr->u8Width, psAttr->u8Width);
  return psAttr->u8Width;
}

void ascii8x8_get_blr(uint8_t *pu8Dest, uint8_t u8Code) {
  uint8_t u8Idx = ascii_code_supported(ASCII_CHRSET_8x8, u8Code) ? u8Code - 32 : 95;
  _rotate_clockwise(pu8Dest, gaau8Ascii8x8[u8Idx]);
}
