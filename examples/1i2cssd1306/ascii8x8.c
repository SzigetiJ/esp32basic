// -------------- Internal functions --------------

static void _rotate_clockwise(uint8_t *pu8Dest, const uint8_t *pu8Src) {
  for (int i = 0; i < 8; ++i) {
    pu8Dest[i] = 0;
    for (int j = 0; j < 8; ++j) {
      pu8Dest[i] |= (pu8Src[j]&(1 << (7 - i)) ? 1 : 0) << j;
    }
  }
}

// -------------- Interface functions --------------

/**
 * Tells whether there is bitmap representation of an ascii code or not.
 * @param u8Code ASCII code.
 * @return The code has bitmap representation.
 */
bool ascii8x8_code_supported(uint8_t u8Code) {
  return 32 <= u8Code && u8Code < 128;
}

/**
 * Puts the bitmap representation to a byte array.
 * The first bit (bit0 of the first byte) is the top left corner, and the bitmap is scanned top down
 * (i.e., MSB of the first byte is the bottom left corner).
 * @param pu8Dest Put the bitmap here.
 * @param u8Code ASCII code of the symbol.
 */
void ascii8x8_get_tld(uint8_t *pu8Dest, uint8_t u8Code) {
  uint8_t u8Idx = ascii8x8_code_supported(u8Code) ? u8Code - 32 : 95;
  memcpy(pu8Dest, gaau8Ascii8x8[u8Idx], 8);
}

void ascii8x8_get_blr(uint8_t *pu8Dest, uint8_t u8Code) {
  uint8_t u8Idx = ascii8x8_code_supported(u8Code) ? u8Code - 32 : 95;
  _rotate_clockwise(pu8Dest, gaau8Ascii8x8[u8Idx]);
}
